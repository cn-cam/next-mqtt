const tables: Record<Locale, Record<string, string>> = { en, zh }

export const locale = ref<Locale>(
  localStorage.getItem('nextmqtt.locale') === 'zh' ? 'zh' : 'en',
)

export function setLocale(value: Locale): void {
  locale.value = value
  localStorage.setItem('nextmqtt.locale', value)
  document.documentElement.lang = value === 'zh' ? 'zh-CN' : 'en'
}

export function toggleLocale(): void {
  setLocale(locale.value === 'en' ? 'zh' : 'en')
}

export function t(key: string, params?: Record<string, string | number>): string {
  let value = tables[locale.value][key] ?? tables.en[key] ?? key

  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.replaceAll(`{${name}}`, String(replacement))
    }
  }

  return value
}
